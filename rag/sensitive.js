const MARGIN = Number(process.env.SENSITIVE_MARGIN || 0.05); // 일반 질문보다 이만큼 더 가까워야 함

let protoP = null;
function prototypes() {
  if (!protoP)
    protoP = (async () => {
      const list = CATEGORIES.flatMap((c) => c.examples.map((e) => ({ key: c.key, text: e })));
      const vecs = await embed([...list.map((x) => x.text), ...NEUTRAL]);
      return { sens: list.map((x, i) => ({ ...x, v: vecs[i] })), neutral: vecs.slice(list.length) };
    })();
  return protoP;
}
const dot = (a, b) => a.reduce((s, x, i) => s + x * b[i], 0);

// 제도 자체를 묻는 일반 질문 ("성희롱 예방교육 몇 시간?", "징계의 종류는?", "초과근무 수당 계산")은
// 키워드가 있어도 본인 상황을 말하는 표현이 없으면 키워드로 확정하지 않고 의미 판단에 맡김
const GENERAL_INFO = /(예방\s*교육|교육\s*(시간|횟수)|종류|절차는|절차\s*알려|규정\s*(이|은)|정의|위원회\s*(구성|위원)|수당\s*(계산|기준|지급\s*기준)|계산\s*(방법|어떻게)|신청\s*(방법|어떻게|하려면)|가입\s*(방법|절차))/;
// 본인이 겪는 상황을 말하는 표현
const PERSONAL_CONTEXT = /(저|제가|저를|저한테|제게|저만|나|내가|나를|나한테|나만|우리\s*(팀|부서|센터)|당했|당하고|받았|받고\s*있|겪고|힘들|무서|어떡|어떻게\s*해야|도와|억울|시켜|하래|하라고)/;
// 주소변경·출국·겸업 같은 행정 "신고"는 고충 신고가 아님
const ADMIN_REPORT = /(주소|신상|가족\s*사항|출국|여권|겸업|외부\s*강의|복무\s*상황|전입|변경|분실|소득|연말\s*정산).{0,15}신고/;

function keywordMatch(t) {
  const adminReport = ADMIN_REPORT.test(t);
  for (const c of CATEGORIES) {
    const hit = (c.words && c.words.test(t)) || (c.patterns && c.patterns.test(t));
    if (!hit) continue;
    if (c.key === '내부고발·신고' && adminReport && !/(고발|제보|익명|노동청)/.test(t)) continue;
    return c.key;
  }
  return null;
}

async function detect(text) {
  const t = String(text || '').trim();
  if (t.length < 4) return { sensitive: false };

  const key = keywordMatch(t);
  if (key && !(GENERAL_INFO.test(t) && !PERSONAL_CONTEXT.test(t))) return { sensitive: true, category: key, via: 'keyword' };

  const { sens, neutral } = await prototypes();
  const [v] = await embed([t]);
  let best = { score: -1 };
  for (const p of sens) {
    const s = dot(v, p.v);
    if (s > best.score) best = { score: s, key: p.key };
  }
  const neutralMax = Math.max(...neutral.map((n) => dot(v, n)));
  const sensitive = best.score >= THRESHOLD && best.score - neutralMax >= MARGIN;
  return {
    sensitive,
    category: sensitive ? best.key : undefined,
    via: 'semantic',
    score: Math.round(best.score * 1000) / 1000,
    neutral: Math.round(neutralMax * 1000) / 1000,
  };
}

module.exports = { detect, keywordMatch, CATEGORIES, warmup: prototypes };
